@lru_cache(maxsize=2048)
def _warn_untranslated(text: str, field_name: str, dictionary: str) -> None:
    """Одна запись для одинакового поля/текста в пределах процесса запуска."""
    logger.warning("Нет русского перевода поля %s: %r. Сохранён исходный текст. Дополните %s.",
                   field_name, text, dictionary)


def translation_key(value: str) -> str:
    return clean_text(value).casefold().rstrip(".")


