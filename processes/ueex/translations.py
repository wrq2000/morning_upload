def translate_document(value: str) -> str:
    original = value
    # Названия компаний и их обозначения внутри имени документа сохраняются.
    protected = {}
    for prefix in ("ГНІ_", "Нордік_"):
        if value.startswith(prefix):
            token = "\u0001{}\u0002".format(len(protected))
            protected[token] = prefix
            value = token + value[len(prefix):]
            break
    for pattern, target in DOCUMENT_PATTERNS_RU:
        def replace(match):
            source = match.group()
            if source.isupper() and not re.search(r"[A-Za-z]", source):
                return target.upper()
            if source.islower():
                return target[0].lower() + target[1:]
            return target
        value = pattern.sub(replace, value)
    # Если полного перевода нет, сохраняем оригинальное имя документа целиком,
    # включая обозначения компаний, и сообщаем об этом в журнале.
    rest = re.sub(r"(?<![A-Za-z])(?:EFET|EGU|UGV|NR|GA|ES|IC)(?![A-Za-z])", "", value)
    if re.search(r"[ІіЇїЄєҐґA-Za-z]", rest):
        _warn_untranslated(original, "document_names", "DOCUMENT_TRANSLATIONS_RU")
        return original
    for token, prefix in protected.items():
        value = value.replace(token, prefix)
    return value


def translate_text(value: Any, field_name: str) -> str:
    text = clean_text(value)
    if not text:
        return text
    if field_name == "document_names":
        return " | ".join(translate_document(part) for part in text.split(" | "))
    key = translation_key(text)
    if key in TRANSLATIONS_RU:
        translated = TRANSLATIONS_RU[key]
        return translated + ("." if text.endswith(".") and not translated.endswith(".") else "")
    if key in {translation_key(target) for target in TRANSLATIONS_RU.values()}:
        return text
    if field_name in {"delivery_point", "delivery_place"} and "," in text:
        return ", ".join(translate_text(part, field_name) for part in text.split(","))
    # Например, условие передачи и отдельная фраза о приобретении мощности.
    sentences = re.split(r"(?<=[.!?])\s+(?=[А-ЯІЇЄҐA-Z])", text)
    if len(sentences) > 1:
        return " ".join(translate_text(part, field_name) for part in sentences)
    _warn_untranslated(text, field_name, "TRANSLATIONS_RU")
    return text

